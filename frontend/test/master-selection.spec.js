import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
import * as XLSX from 'xlsx';
test('master list checkboxes export only marked rows and delete together after confirmation',async({page,request})=>{
 const endpoint='http://localhost:8787';
 let token;
 const call=async(action,payload={})=>{const r=await request.post(endpoint,{data:{action,payload,token}});const b=await r.json();expect(b.ok,b.error).toBe(true);return b.data;};
 token=(await call('login',{username:'admin',password:'admin123'})).token;
 await call('master.save',{kind:'brand',name:'Marked Alpha'});await call('master.save',{kind:'brand',name:'Marked Beta'});
 await page.addInitScript(({endpoint,token})=>{localStorage.setItem('erp_api_config',JSON.stringify({scriptUrl:endpoint}));localStorage.setItem('erp_token',token);},{endpoint,token});
 await page.goto('/#/stock');await page.getByRole('tab',{name:'Categories, brands & warranty'}).click();
 const panel=page.locator('.md-panel').filter({has:page.getByRole('heading',{name:'Brands',exact:true})});
 await panel.getByRole('checkbox',{name:'Select Marked Alpha',exact:true}).check();
 await expect(panel.getByRole('button',{name:'Rename Marked Alpha',exact:true})).toHaveText('');
 await expect(panel.getByRole('button',{name:'Export Brands',exact:true})).toHaveText('');
 await panel.getByRole('button',{name:'Export Brands',exact:true}).click();
 const download=page.waitForEvent('download');await panel.getByRole('menuitem',{name:'Excel (.xlsx)',exact:true}).click();
 const file=await download;const wb=XLSX.read(await fs.readFile(await file.path()));
 const rows=XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]],{header:1}).flat().map(String);
 expect(rows).toContain('Marked Alpha');expect(rows).not.toContain('Marked Beta');
 await panel.getByRole('checkbox',{name:'Select Marked Beta',exact:true}).check();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true);
 await panel.getByRole('button',{name:'Delete selected Brands',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(panel.getByRole('checkbox',{name:'Select Marked Alpha',exact:true})).toBeChecked();
 await panel.getByRole('button',{name:'Delete selected Brands',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Delete',exact:true}).click();
 await expect(panel.getByRole('checkbox',{name:'Select Marked Alpha',exact:true})).toHaveCount(0);
 await expect(panel.getByRole('checkbox',{name:'Select Marked Beta',exact:true})).toHaveCount(0);
});
