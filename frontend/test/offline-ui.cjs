const { _electron } = require('playwright');
const { expect } = require('@playwright/test');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'karvio-offline-ui-'));
let desktop, page;
const networkRequests = [];
const launch = async () => {
  const executablePath = process.env.KARVIO_PACKAGED_EXE || process.env.KARVIO_ELECTRON_EXECUTABLE || require('electron');
  desktop = await _electron.launch({ executablePath, args: process.env.KARVIO_PACKAGED_EXE ? ['--offline'] : [path.resolve(__dirname, '..'), '--offline'], env: { ...process.env, KARVIO_DATA_DIR: dataDir, KARVIO_TEST_MODE: '1' }, timeout: 30000 });
  page = await desktop.firstWindow();
  page.on('pageerror', (error) => console.error('Offline window:', error.message));
  page.on('request', (request) => { if (/^https?:/.test(request.url())) networkRequests.push(request.url()); });
  await page.context().setOffline(true);
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible();
  await page.getByLabel('Username', { exact: true }).fill('admin');
  await page.getByLabel('Password', { exact: true }).fill('admin123');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.locator('.page-head h1')).toHaveText('Dashboard');
};
const call = (action, payload = {}) => page.evaluate(async ({ action, payload }) => {
  const r = await window.karvio.request({ action, payload, token: localStorage.getItem('erp_token') });
  if (!r.ok) throw new Error(r.error); return r.data;
}, { action, payload });

(async () => {
  await launch();
  await expect(page.getByText('Offline · saved on this PC', { exact: true })).toBeVisible();
  const cash = (await call('bootstrap')).accounts[0];
  const pr = await call('product.save', { name: 'বাংলা অফলাইন কেবল', unit: 'meter', sale_price: 30 });
  await call('purchase.create', { items: [{ product_id: pr.id, qty: 100, cost: 20 }], payments: [{ account_id: cash.id, amount: 2000 }] });
  await call('sale.create', { items: [{ product_id: pr.id, qty: 2.5, price: 30 }], payments: [{ account_id: cash.id, amount: 75 }] });
  await desktop.close();
  await launch();
  assert.equal((await call('products.list')).find((p) => p.id === pr.id).stock, 97.5);
  assert.equal((await call('accounts.list')).find((a) => a.id === cash.id).balance, -1925);
  await page.evaluate(() => { location.hash = '#/stock'; });
  await expect(page.getByText('বাংলা অফলাইন কেবল', { exact: true })).toBeVisible();
  const pdfPath = path.join(dataDir, 'bengali-offline.pdf');
  await desktop.evaluate(({ session }, target) => { session.defaultSession.once('will-download', (_, item) => item.setSavePath(target)); }, pdfPath);
  await page.getByRole('button', { name: 'PDF', exact: true }).click();
  await expect.poll(() => fs.existsSync(pdfPath) ? fs.statSync(pdfPath).size : 0, { timeout: 30000 }).toBeGreaterThan(10000);
  assert.ok(fs.statSync(pdfPath).size > 10000);
  await page.evaluate(() => { location.hash = '#/settings'; });
  await page.getByRole('tab', { name: 'Offline data & backup' }).click();
  await expect(page.getByRole('button', { name: 'Save backup', exact: true })).toBeVisible();
  await expect(page.getByRole('tab', { name: 'API connection' })).toHaveCount(0);
  await expect(page.getByRole('tab', { name: 'SMS gateway' })).toHaveCount(0);
  const backup = path.join(dataDir, 'ui-backup.json');
  await desktop.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, backup);
  await page.getByRole('button', { name: 'Save backup', exact: true }).click();
  await expect(page.getByText('Backup saved', { exact: true })).toBeVisible();
  assert.ok(fs.existsSync(backup));
  await call('product.save', { name: 'After UI backup' });
  await desktop.evaluate(({ dialog }, filePath) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filePath] }); dialog.showMessageBox = async () => ({ response: 1 }); }, backup);
  await page.getByRole('button', { name: 'Restore backup', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible();
  await page.getByLabel('Username', { exact: true }).fill('admin'); await page.getByLabel('Password', { exact: true }).fill('admin123');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.locator('.page-head h1')).toBeVisible();
  await page.evaluate(() => { location.hash = '#/'; });
  await expect(page.locator('.page-head h1')).toHaveText('Dashboard');
  assert.equal((await call('products.list')).some((p) => p.name === 'After UI backup'), false);
  assert.equal(networkRequests.length, 0, 'The offline ERP must make zero internet requests');
  fs.mkdirSync(path.resolve(__dirname, '../../verification'), { recursive: true });
  await page.screenshot({ path: path.resolve(__dirname, '../../verification/offline-desktop.png') });
  console.log('Offline desktop passed: restart persistence, stock/accounts, Bengali PDF, backup/restore, zero internet requests');
})().catch((error) => { console.error(error); process.exitCode = 1; }).finally(async () => { if (desktop) await desktop.close(); });
