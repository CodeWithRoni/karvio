const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { OfflineRuntime } = require('../../frontend/desktop/offline-runtime.cjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'karvio-offline-test-'));
const options = { dataDir: dir, codePath: path.join(__dirname, '..', 'Code.gs') };
let app = new OfflineRuntime(options), token, checks = 0;
const equal = (a, b) => { assert.deepEqual(a, b); checks++; };
const call = (action, payload = {}) => { const r = app.execute({ action, payload, token }); assert.equal(r.ok, true, r.error); return r.data; };
const login = () => { token = call('login', { username: 'admin', password: 'admin123' }).token; };
login();
const cash = call('bootstrap').accounts[0];
const supplier = call('supplier.save', { name: 'Offline supplier' });
const customer = call('customer.save', { name: 'Offline customer' });
const group = call('master.save', { kind: 'group', name: 'OFFLINE PROCESSOR' });
const category = call('master.save', { kind: 'category', name: 'INTEL', parent_id: group.id });
const product = call('product.save', { name: 'বাংলা অফলাইন পণ্য', unit: 'pcs', sale_price: 150, category_id: group.id, subcategory_id: category.id });
call('purchase.create', { supplier_id: supplier.id, items: [{ product_id: product.id, qty: 5, cost: 100 }], payments: [{ account_id: cash.id, amount: 500 }] });
const sale = call('sale.create', { customer_id: customer.id, items: [{ product_id: product.id, qty: 1, price: 150 }], payments: [{ account_id: cash.id, amount: 100 }] });
equal(call('products.list').find((p) => p.id === product.id).stock, 4);
equal(call('customers.list').find((c) => c.id === customer.id).balance, 50);
equal(call('accounts.list').find((a) => a.id === cash.id).balance, -400);
assert.ok(fs.existsSync(app.file)); checks++;
app = new OfflineRuntime(options); login();
equal(call('products.list').find((p) => p.id === product.id).stock, 4);
equal(call('customers.list').find((c) => c.id === customer.id).balance, 50);
equal(call('sale.detail', { id: sale.sale.id }).sale.total, 150);
equal(call('accounts.list').find((a) => a.id === cash.id).balance, -400);
assert.ok(fs.existsSync(app.previousFile)); checks++;
assert.ok(fs.readdirSync(app.backupDir).some((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f))); checks++;

// A failure after stock, invoice and account writes must roll back all tables.
const before = fs.readFileSync(app.file, 'utf8');
const acct = app.context.acctTxn_;
app.context.acctTxn_ = (...args) => { acct(...args); throw new Error('Simulated write failure'); };
const failed = app.execute({ action: 'sale.create', token, payload: { items: [{ product_id: product.id, qty: 1, price: 150 }], payments: [{ account_id: cash.id, amount: 150 }] } });
equal(failed.ok, false);
equal(fs.readFileSync(app.file, 'utf8'), before);
equal(call('products.list').find((p) => p.id === product.id).stock, 4);
equal(call('accounts.list').find((a) => a.id === cash.id).balance, -400);
app.context.acctTxn_ = acct;
const persist = app.persist;
app.persist = () => { throw new Error('Disk unavailable'); };
equal(app.execute({ action: 'product.save', token, payload: { name: 'Must not be saved' } }).ok, false);
app.persist = persist;
equal(call('products.list').some((p) => p.name === 'Must not be saved'), false);

const backup = path.join(dir, 'export.json');
app.exportBackup(token, backup);
const later = call('product.save', { name: 'After backup' });
const restored = app.restoreBackup(token, backup);
assert.ok(fs.existsSync(restored.safetyBackup)); checks++;
equal(app.execute({ action: 'bootstrap', token }).ok, false);
login();
equal(call('products.list').some((p) => p.id === later.id), false);
equal(call('products.list').find((p) => p.id === product.id).stock, 4);
const invalid = path.join(dir, 'invalid.json'); fs.writeFileSync(invalid, '{}');
assert.throws(() => app.restoreBackup(token, invalid), /valid Karvio/); checks++;
equal(call('products.list').find((p) => p.id === product.id).stock, 4);
call('user.save', { name: 'Staff', username: 'staff', password: 'secret123', role: 'sales' });
const staff = app.execute({ action: 'login', payload: { username: 'staff', password: 'secret123' } }).data.token;
assert.throws(() => app.exportBackup(staff, path.join(dir, 'unauthorized.json')), /administrator/); checks++;
call('settings.save', { values: { sms_enabled: 'true', sms_url: 'https://example.invalid/sms', sms_api_key: 'test' } });
const sms = app.execute({ action: 'sms.test', token, payload: { phone: '01700000000' } });
equal(sms.ok, false);
assert.match(sms.error, /offline mode/); checks++;
app = new OfflineRuntime(options); login();
equal(call('bootstrap').settings.sms_enabled, 'false');
call('reverse', { type: 'sale', id: sale.sale.id, reason: 'Offline reversal', password: 'admin123' });
equal(call('products.list').find((p) => p.id === product.id).stock, 5);
equal(call('customers.list').find((c) => c.id === customer.id).balance, 0);
equal(call('accounts.list').find((a) => a.id === cash.id).balance, -500);
const corruptDir = fs.mkdtempSync(path.join(os.tmpdir(), 'karvio-corrupt-test-'));
const corruptFile = path.join(corruptDir, 'shop-erp.json'); fs.writeFileSync(corruptFile, 'not-json');
assert.throws(() => new OfflineRuntime({ ...options, dataDir: corruptDir })); checks++;
equal(fs.readFileSync(corruptFile, 'utf8'), 'not-json');
console.log('Persistent offline database: ' + checks + ' checks passed');
