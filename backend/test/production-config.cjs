const fs=require('node:fs'),assert=require('node:assert/strict');
const YAML=require('../../frontend/node_modules/yaml');
const config=YAML.parse(fs.readFileSync('.github/workflows/deploy.yml','utf8'));
assert.deepEqual(config.jobs['deploy-backend'].needs,'build-and-test');
assert.deepEqual(config.jobs['publish-frontend'].needs,['build-and-test','deploy-backend']);
const steps=config.jobs['deploy-backend'].steps;
const at=name=>steps.findIndex(s=>s.name===name);
assert.ok(at('Apply tested migrations before Edge deployment')<at('Deploy karvio-api'));
assert.ok(at('Deploy karvio-api')<at('Verify exact backend revision'));
assert.match(steps[at('Verify exact backend revision')].run,/buildId/);
assert.match(steps[at('Require deploy credentials')].run,/exit 1/);
assert.equal(config.concurrency['cancel-in-progress'],false);
assert.ok(!config.jobs['build-and-test'].steps.some(s=>s.run?.includes('git push')));
const version=JSON.parse(fs.readFileSync('frontend/package.json')).version;
const tauri=JSON.parse(fs.readFileSync('frontend/src-tauri/tauri.conf.json'));
assert.equal(tauri.version,version);assert.ok(fs.readFileSync('backend/Code.gs','utf8').includes("var APP_VERSION = '"+version+"';"));
assert.ok(tauri.app.security.csp.includes("script-src 'self'"));assert.ok(!tauri.app.security.csp.includes('unsafe-eval'));
assert.ok(!fs.readFileSync('supabase/functions/karvio-api/index.ts','utf8').includes('x-forwarded-for'));
assert.ok(!fs.existsSync('backend/parts/01_core.gs'));
console.log('Production configuration passed: gated deploy graph, exact build identity, explicit CSP, header-independent limiting and canonical backend.');
