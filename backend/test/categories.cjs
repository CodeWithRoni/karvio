const fs = require('fs');
const path = require('path');
const harness = fs.readFileSync(path.join(__dirname, 'simulate.js'), 'utf8').split('/* ---------------- scenario ---------------- */')[0];
const scenario = `
sandbox.setupDatabase();
const assert = require('node:assert/strict');
const token = call('login',{username:'admin',password:'admin123'}).data.token;
const A = (action,payload={}) => {const r=call(action,payload,token);assert.equal(r.ok,true,r.error);return r.data;};
let checks=0;
const equal=(a,b)=>{assert.deepEqual(a,b);checks++;};
const denied=(action,payload,pattern)=>{const r=call(action,payload,token);assert.equal(r.ok,false);assert.match(r.error,pattern);checks++;};
const legacy=A('bootstrap').categories;
const group=A('master.save',{kind:'group',name:' PROCESSOR '});
equal(group.name,'PROCESSOR');
equal(group.parent_id,'');
const intel=A('master.save',{kind:'category',name:'INTEL',parent_id:group.id});
const amd=A('master.save',{kind:'category',name:'AMD',parent_id:group.id});
equal(intel.parent_id,group.id);
equal(amd.parent_id,group.id);
denied('master.save',{kind:'category',name:'Orphan'},/product group/i);
denied('master.save',{kind:'category',name:'Nested',parent_id:intel.id},/product group/i);
denied('master.save',{kind:'category',name:'Missing group',parent_id:'unknown'},/product group/i);
denied('master.save',{kind:'group',name:' processor '},/already exists/i);
denied('master.save',{kind:'category',name:' intel ',parent_id:group.id},/already exists/i);
const other=A('master.save',{kind:'group',name:'MOTHERBOARD'});
equal(A('master.save',{kind:'category',name:'INTEL',parent_id:other.id}).parent_id,other.id);
denied('master.delete',{kind:'group',id:group.id},/in use/i);
denied('master.delete',{kind:'category',id:group.id},/correct product group/i);
denied('master.save',{kind:'group',id:intel.id,name:'Wrong editor'},/not a product group/i);
denied('product.save',{name:'Wrong mapping',category_id:other.id,subcategory_id:intel.id},/must belong/i);
denied('product.save',{name:'Wrong group',category_id:intel.id},/valid product group/i);
const pr=A('product.save',{name:'Core i5',unit:'pcs',category_id:group.id,subcategory_id:intel.id});
equal(pr.category_id,group.id);
equal(pr.subcategory_id,intel.id);
denied('master.delete',{kind:'category',id:intel.id},/in use/i);
denied('master.save',{kind:'category',id:intel.id,name:'INTEL',parent_id:other.id},/cannot be moved/i);
A('master.save',{kind:'category',id:amd.id,name:'AMD RYZEN',parent_id:group.id});
equal(A('bootstrap').categories.find(c=>c.id===amd.id).name,'AMD RYZEN');
A('master.delete',{kind:'category',id:amd.id});
equal(A('bootstrap').categories.some(c=>c.id===amd.id),false);
equal(A('bootstrap').categories.filter(c=>legacy.some(old=>old.id===c.id)),legacy);
console.log('Product group/category regression: '+checks+' checks passed');
`;
new Function('require','__dirname',harness+scenario)(require,__dirname);
