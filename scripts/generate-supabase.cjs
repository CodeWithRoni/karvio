// Applied migrations are immutable. --schema is only for the initial, unapplied
// migration; later database changes need a NEW CLI-generated migration.
if (process.argv.includes('--schema')) fs.writeFileSync(path.join(root, 'supabase/migrations', migrations[0]), sql);
console.log(`Generated ${Object.keys(schema).length} table definitions and static ERP engine${process.argv.includes('--schema') ? ' plus initial migration' : '; historical migrations unchanged'}.`);
